#!/usr/bin/env node
// Mission 14 Etape 3 -- migrate existing pilot access keys (Mission 06,
// ACCESS_KEY_HASHES) into the D1 `licenses` table (tier "individual",
// max_devices 1). NOT run automatically by any other script or CI step --
// this is a one-time, manually-invoked tool for the day Massy is ready to
// cut real pilots over from the env-var gate to the license system (see
// docs/LICENCES.md #6 "ce qui n'est pas encore fait").
//
// Usage:
//   node scripts/migrate-keys-to-d1.mjs keys/<timestamp>.csv [keys/<other>.csv ...]
//   node scripts/migrate-keys-to-d1.mjs keys/*.csv
//
// Reads clear-text keys from the CSV files scripts/generate-keys.mjs
// already produces (key,hash columns; see keys/ -- gitignored, never
// committed). Writes a ready-to-run SQL file (does NOT execute it itself,
// and NEVER touches --remote on its own -- migrating production data is a
// deliberate, separate, manually-confirmed action):
//
//   node scripts/migrate-keys-to-d1.mjs keys/*.csv > migrations/9999_pilot_keys.sql
//   npx wrangler d1 execute gds-licences --local --file=migrations/9999_pilot_keys.sql   # verify locally first
//   npx wrangler d1 execute gds-licences --remote --file=migrations/9999_pilot_keys.sql  # only once verified
//
// After the cutover is verified in production, remove ACCESS_KEY_HASHES
// from the Cloudflare Pages project and stop importing this script's
// output anywhere -- it is a bridge, not a permanent part of the system.

import { readFileSync } from "node:fs";

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error("Usage: node scripts/migrate-keys-to-d1.mjs keys/*.csv > migrations/9999_pilot_keys.sql");
  process.exit(1);
}

const hashes = new Set();
for (const file of files) {
  const content = readFileSync(file, "utf8");
  const lines = content.trim().split("\n").slice(1); // drop the "key,hash" header
  for (const line of lines) {
    const [, hash] = line.split(",");
    if (hash) hashes.add(hash.trim());
  }
}

const statements = [...hashes].map(
  (hash) =>
    `INSERT INTO licenses (key_hash, tier, max_devices, client_name) VALUES ('${hash}', 'individual', 1, 'pilote') ON CONFLICT (key_hash) DO NOTHING;`
);

console.log("-- Generated by scripts/migrate-keys-to-d1.mjs -- review before running --remote.");
console.log(`-- ${statements.length} pilot key(s) from: ${files.join(", ")}`);
console.log(statements.join("\n"));
